using ProtocolWorkbench.Core.Enums;
using ProtocolWorkbench.Core.Models;
using System.Text;

namespace ProtocolWorkbench.Core.Services.CodeGen;

public sealed class AppParamsFirmwareGenerator : IAppParamsFirmwareGenerator
{
    public (string Header, string Source) Generate(ParamYamlDoc doc)
    {
        doc.Params ??= new List<ParamYamlItem>();
        var ps = doc.Params.OrderBy(p => p.Id).ToList();

        var h = GenerateHeader(doc, ps);
        var c = GenerateSource(doc, ps);

        return (h, c);
    }

