        sb.AppendLine("\tswitch ((app_param_id_t)id) {");

        foreach (var p in defaults)
        {
            sb.AppendLine($"\tcase {ToParamEnumName(p)}:");
            sb.Append(GenerateDefaultCaseBody(p));
