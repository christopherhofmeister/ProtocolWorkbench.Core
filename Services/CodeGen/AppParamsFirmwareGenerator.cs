        sb.AppendLine("\t\treturn APP_PARAM_STATUS_INVALID_ARG;");
        sb.AppendLine("\t}");
        sb.AppendLine();

        if (defaults.Count == 0)
        {
            sb.AppendLine("\tARG_UNUSED(id);");
            sb.AppendLine("\tARG_UNUSED(out_value_max);");
            sb.AppendLine("\treturn APP_PARAM_STATUS_NOT_FOUND;");
            sb.AppendLine("}");
            sb.AppendLine();
